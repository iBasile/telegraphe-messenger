import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const serverRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const protoPath = path.resolve(serverRoot, '../proto/telegraphe.proto');
const outputPath = path.resolve(serverRoot, 'src/generated/telegraphe.ts');
const protoHash = createHash('sha256').update(await readFile(protoPath)).digest('hex');

await new Promise((resolve, reject) => {
  const child = spawn(
    'protoc',
    [
      '--plugin=protoc-gen-ts_proto=./node_modules/.bin/protoc-gen-ts_proto',
      '--ts_proto_out=src/generated',
      '--ts_proto_opt=esModuleInterop=true,outputEncodeMethods=true,outputJsonMethods=false,outputClientImpl=false,forceLong=number,useOptionals=all',
      '-I',
      '../proto',
      '../proto/telegraphe.proto',
    ],
    { cwd: serverRoot, stdio: 'inherit' },
  );
  child.on('error', reject);
  child.on('exit', (code) => (code === 0 ? resolve() : reject(new Error(`protoc exited with ${code}`))));
});

const generated = await readFile(outputPath, 'utf8');
const compatibility = `

type LegacyCodec<T> = {
  encode(value: T): { finish(): Uint8Array };
  decode(data: Uint8Array): T;
};

const legacyCodec = <T>(message: MessageFns<T>): LegacyCodec<T> => ({
  encode: (value) => ({ finish: () => message.encode(value).finish() }),
  decode: (data) => message.decode(data),
});

export const EnvelopeCodec = legacyCodec(Envelope);
export const HandshakeCodec = legacyCodec(Handshake);
export const HandshakeAckCodec = legacyCodec(HandshakeAck);
export const TextMessageCodec = legacyCodec(TextMessage);
export const MediaMessageCodec = legacyCodec(MediaMessage);
export const ServerAckCodec = legacyCodec(ServerAck);
export const ReceiptCodec = legacyCodec(Receipt);
export const TypingCodec = legacyCodec(Typing);
export const PresenceCodec = legacyCodec(Presence);
export const ErrorCodec = legacyCodec(Error);
export const SystemEventCodec = legacyCodec(SystemEvent);
`;
await writeFile(
  outputPath,
  generated.replace(
    '// Code generated by protoc-gen-ts_proto. DO NOT EDIT.',
    `// Code generated by protoc-gen-ts_proto. DO NOT EDIT.\n// proto-sha256: ${protoHash}`,
  ) + compatibility,
);
